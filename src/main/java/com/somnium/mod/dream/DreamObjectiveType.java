package com.somnium.mod.dream;

/**
 * ИСПРАВЛЕНИЕ ("задание сна нельзя выполнить"): раньше DreamType#objective() был ЧИСТО текстовым
 * полем — красивая строка цели показывалась в HUD, но НИЧТО в коде её не проверяло. Игрок мог
 * буквально сделать всё, что написано в подсказке (дойти до маяка, собрать осколки, убить
 * двойника) — и ничего не происходило: сон завершался только по таймауту или по смерти, а
 * DreamOutcome.SURVIVED_OBJECTIVE и WOKE_EARLY существовали в SanityManager, но ни разу не
 * вызывались из кода. Этот enum — способ данных описать, КАК именно проверяется цель конкретного
 * сна, чтобы DreamManager мог реально её отследить и досрочно разбудить игрока с наградой.
 */
public enum DreamObjectiveType {
    /**
     * Дойти до определённой точки локации ("Дверь пробуждения") — используется для целей вида
     * "добраться до X", "отступить к Y". DreamManager спавнит в этой точке маркер (ArmorStand)
     * и следит за расстоянием игрока до неё каждый тик.
     */
    REACH_DOOR,

    /**
     * Собрать N предметов определённого типа (DreamType#objectiveTargetId), заранее
     * разбросанных по локации при входе в сон. Проверяется по количеству предмета в
     * инвентаре игрока (инвентарь на входе в сон пуст — см. DreamManager#snapshotAndClearInventory).
     */
    COLLECT_ITEMS,

    /**
     * Победить конкретную сущность (DreamType#objectiveTargetId) — заспавненную гарантированно
     * ОДИН раз как "боец цели" (в отличие от рядовых монстров сна, которых может быть несколько).
     * DreamManager запоминает UUID этого конкретного экземпляра и следит, жив ли он ещё.
     */
    BOSS_KILL
}
